#!/usr/bin/env python3
"""Generate the pure-Rust title-demo data from the checked-in C sources.

The generator intentionally parses only the two declarations in each source
file.  It does not compile C or invoke a C compiler.  The output is stable so
that a review can compare the generated Rust directly with the source values.
"""

from __future__ import annotations

import hashlib
import re
import sys
from pathlib import Path


ROOT = Path(__file__).resolve().parents[2]
SOURCE_DIR = ROOT / "src/data/titledemo"
OUTPUT = ROOT / "rust/nookery-data-assets/src/generated.rs"
MANIFEST = ROOT / "rust/nookery-data-assets/source-manifest.txt"
EXPECTED_NAMES = tuple(
    f"pact{demo}_{kind}"
    for demo in range(5)
    for kind in ("head_table", "key_data")
)
DECLARATION = re.compile(
    r"\bu16\s+(pact[0-4]_(?:head_table|key_data))\s*\[\s*\]\s*=\s*\{(?P<body>.*?)\};",
    re.DOTALL,
)
HEX = re.compile(r"0[xX]([0-9a-fA-F]+)")


def parse_values(source: str, path: Path) -> dict[str, list[int]]:
    without_comments = re.sub(r"/\*.*?\*/|//[^\n]*", "", source, flags=re.DOTALL)
    found: dict[str, list[int]] = {}
    for match in DECLARATION.finditer(without_comments):
        name = match.group(1)
        values = [int(token, 16) for token in HEX.findall(match.group("body"))]
        if not values or any(value > 0xFFFF for value in values):
            raise SystemExit(f"invalid u16 values in {path}: {name}")
        if name in found:
            raise SystemExit(f"duplicate declaration in {path}: {name}")
        found[name] = values
    if set(found) != {path.stem + "_head_table", path.stem + "_key_data"}:
        raise SystemExit(f"unexpected declarations in {path}: {sorted(found)}")
    return found


def canonical_bytes(values: list[int]) -> bytes:
    return b"".join(value.to_bytes(2, "big") for value in values)


def render_array(name: str, values: list[int]) -> str:
    prefix = f"#[unsafe(no_mangle)]\npub static {name}: [u16; {len(values)}] = "
    if len(values) <= 6:
        return prefix + "[" + ", ".join(f"0x{value:04X}" for value in values) + "];\n"
    lines = [prefix + "["]
    for offset in range(0, len(values), 12):
        lines.append("    " + ", ".join(f"0x{value:04X}" for value in values[offset : offset + 12]) + ",")
    lines.append("];\n")
    return "\n".join(lines)


def generate() -> tuple[str, str]:
    sources = sorted(SOURCE_DIR.glob("*.c"))
    if [path.stem for path in sources] != [f"pact{demo}" for demo in range(5)]:
        raise SystemExit("src/data/titledemo must contain exactly pact0.c through pact4.c")

    parsed: dict[str, list[int]] = {}
    manifest_lines = [
        "# Generated by tools/titledemo/generate_rust.py; paths are repository-relative.",
        "# source_sha256 is the raw C source; data_sha256 is canonical big-endian u16 data.",
    ]
    for path in sources:
        values = parse_values(path.read_text(encoding="utf-8"), path)
        parsed.update(values)
        head = values[f"{path.stem}_head_table"]
        keys = values[f"{path.stem}_key_data"]
        source_hash = hashlib.sha256(path.read_bytes()).hexdigest()
        data_hash = hashlib.sha256(canonical_bytes(head + keys)).hexdigest()
        manifest_lines.append(
            f"{path.relative_to(ROOT)}\tsource_sha256={source_hash}\t"
            f"data_sha256={data_hash}\thead_words={len(head)}\tkey_words={len(keys)}"
        )

    if tuple(parsed) != EXPECTED_NAMES:
        raise SystemExit(f"missing or unexpected title-demo identifiers: {sorted(parsed)}")

    generated = """// @generated by tools/titledemo/generate_rust.py; do not edit by hand.
//
// Source scope: src/data/titledemo/pact0.c through pact4.c.
// The source uses `u16`, which is an unsigned 16-bit scalar in include/types.h.
// These arrays intentionally retain the source identifiers and element sizes.

#![allow(non_upper_case_globals)]

"""
    for name in EXPECTED_NAMES:
        generated += render_array(name, parsed[name])
    return generated, "\n".join(manifest_lines) + "\n"


def main() -> int:
    generated, manifest = generate()
    check = "--check" in sys.argv[1:]
    if check:
        current_output = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        current_manifest = MANIFEST.read_text(encoding="utf-8") if MANIFEST.exists() else ""
        if current_output != generated or current_manifest != manifest:
            print("generated title-demo files are stale", file=sys.stderr)
            return 1
    else:
        OUTPUT.parent.mkdir(parents=True, exist_ok=True)
        OUTPUT.write_text(generated, encoding="utf-8")
        MANIFEST.parent.mkdir(parents=True, exist_ok=True)
        MANIFEST.write_text(manifest, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
