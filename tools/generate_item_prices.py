#!/usr/bin/env python3
"""Generate Rust item-price tables by strictly parsing the C oracle."""

from __future__ import annotations

import argparse
import hashlib
import re
import subprocess
import sys
from dataclasses import dataclass
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
GENERATED = ROOT / "rust/nookery-item-data/src/generated.rs"
MANIFEST = ROOT / "rust/nookery-item-data/SOURCE_MANIFEST.toml"
SOURCES = (
    ("src/data/item/md_price.c", "md_price_table"),
    ("src/data/item/plant_price.c", "plant_price_table"),
    ("src/data/item/insect_price.c", "insect_price_table"),
    ("src/data/item/fish_price.c", "fish_price_table"),
    ("src/data/item/food_price.c", "food_price_table"),
)
DECLARATION = re.compile(
    r"\Aunsigned short\s+([A-Za-z_][A-Za-z0-9_]*)(?:\[(\d*)\])?\s*=\s*\{(.*)\};\s*\Z",
    re.DOTALL,
)
INTEGER = re.compile(r"\A-?[0-9]+\Z")


@dataclass(frozen=True)
class Table:
    path: str
    symbol: str
    declared_len: int | None
    source_bytes: int
    source_sha256: str
    values: tuple[int, ...]
    values_fnv1a64: int


def fnv1a64(data: bytes) -> int:
    value = 0xCBF29CE484222325
    for byte in data:
        value ^= byte
        value = (value * 0x100000001B3) & 0xFFFFFFFFFFFFFFFF
    return value


def parse_table(relative_path: str, expected_symbol: str) -> Table:
    path = ROOT / relative_path
    raw = path.read_bytes()
    match = DECLARATION.fullmatch(raw.decode("ascii"))
    if match is None:
        raise ValueError(f"{relative_path}: not a supported unsigned-short table declaration")
    symbol, declared_len_text, body = match.groups()
    if symbol != expected_symbol:
        raise ValueError(f"{relative_path}: expected {expected_symbol}, found {symbol}")

    tokens = [token.strip() for token in body.split(",")]
    if tokens and tokens[-1] == "":
        tokens.pop()
    if not tokens or any(not INTEGER.fullmatch(token) for token in tokens):
        raise ValueError(f"{relative_path}: initializer contains a non-integer token")
    source_values = tuple(int(token) for token in tokens)
    if source_values[-1] != -1:
        raise ValueError(f"{relative_path}: missing terminating -1 sentinel")
    if -1 in source_values[:-1]:
        raise ValueError(f"{relative_path}: -1 sentinel appears before the final entry")
    if any(value < -1 or value > 0xFFFF for value in source_values):
        raise ValueError(f"{relative_path}: value outside unsigned-short range")
    values = tuple(0xFFFF if value == -1 else value for value in source_values)
    declared_len = int(declared_len_text) if declared_len_text else None
    if declared_len is not None and declared_len != len(values):
        raise ValueError(
            f"{relative_path}: declaration length {declared_len} != {len(values)} initializers"
        )
    value_bytes = b"".join(value.to_bytes(2, "little") for value in values)
    return Table(
        path=relative_path,
        symbol=symbol,
        declared_len=declared_len,
        source_bytes=len(raw),
        source_sha256=hashlib.sha256(raw).hexdigest(),
        values=values,
        values_fnv1a64=fnv1a64(value_bytes),
    )


def tables() -> tuple[Table, ...]:
    return tuple(parse_table(path, symbol) for path, symbol in SOURCES)


def rust_table_name(symbol: str) -> str:
    return symbol.upper()


def render_rust(parsed: tuple[Table, ...]) -> str:
    lines = [
        "//! Generated by tools/generate_item_prices.py; do not edit by hand.",
        "",
        "/// Exact source and generated-value metadata for one C price table.",
        "#[derive(Clone, Copy, Debug, Eq, PartialEq)]",
        "pub struct SourceManifest {",
        "    pub source_path: &'static str,",
        "    pub symbol: &'static str,",
        "    pub declared_len: Option<usize>,",
        "    pub entry_count: usize,",
        "    pub source_bytes: usize,",
        "    pub source_sha256: &'static str,",
        "    pub values_fnv1a64: u64,",
        "}",
        "",
    ]
    for table in parsed:
        lines.extend(
            [
                "#[allow(non_upper_case_globals)]",
                f"pub const {table.symbol}: &[u16] = &[",
                *[f"    {value}," for value in table.values],
                "];",
                f"pub const {rust_table_name(table.symbol)}: &[u16] = {table.symbol};",
                "",
            ]
        )
    lines.extend(
        [
            "pub const SOURCE_MANIFEST: &[SourceManifest] = &[",
            *[
                "    SourceManifest {\n"
                f"        source_path: \"{table.path}\",\n"
                f"        symbol: \"{table.symbol}\",\n"
                f"        declared_len: {'Some(' + str(table.declared_len) + ')' if table.declared_len is not None else 'None'},\n"
                f"        entry_count: {len(table.values)},\n"
                f"        source_bytes: {table.source_bytes},\n"
                f"        source_sha256: \"{table.source_sha256}\",\n"
                f"        values_fnv1a64: 0x{table.values_fnv1a64:016x},\n"
                "    },"
                for table in parsed
            ],
            "];",
            "",
        ]
    )
    return "\n".join(lines)


def render_manifest(parsed: tuple[Table, ...]) -> str:
    lines = [
        "# Generated by tools/generate_item_prices.py; do not edit by hand.",
        "# source_sha256 hashes the exact C bytes; values_fnv1a64 hashes little-endian u16 values.",
        "",
    ]
    for table in parsed:
        lines.extend(
            [
                "[[table]]",
                f'source_path = "{table.path}"',
                f'symbol = "{table.symbol}"',
                f"declared_len = {table.declared_len if table.declared_len is not None else 0}",
                f"declared_len_is_explicit = {str(table.declared_len is not None).lower()}",
                f"entry_count = {len(table.values)}",
                f"source_bytes = {table.source_bytes}",
                f'source_sha256 = "{table.source_sha256}"',
                f'values_fnv1a64 = "{table.values_fnv1a64:016x}"',
                "",
            ]
        )
    return "\n".join(lines)


def format_rust(source: str) -> str:
    result = subprocess.run(
        ["rustfmt", "--edition", "2024", "--emit", "stdout"],
        input=source,
        text=True,
        capture_output=True,
        check=False,
    )
    if result.returncode != 0:
        raise RuntimeError(f"rustfmt failed: {result.stderr}")
    return result.stdout


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="fail if generated files are stale")
    args = parser.parse_args()
    parsed = tables()
    expected = {
        GENERATED: format_rust(render_rust(parsed)),
        MANIFEST: render_manifest(parsed),
    }
    stale = False
    for path, content in expected.items():
        if args.check:
            if not path.is_file() or path.read_text() != content:
                print(f"stale generated file: {path}", file=sys.stderr)
                stale = True
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
            print(f"wrote {path}")
    return 1 if stale else 0


if __name__ == "__main__":
    raise SystemExit(main())
